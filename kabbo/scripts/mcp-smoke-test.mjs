#!/usr/bin/env node
/**
 * MCP smoke test: calls every tool on the deployed Kabbo MCP server with a
 * throwaway API key and checks that each one answers without an error.
 *
 * Why this exists: the MCP tools talk to Postgres with the service role, so a
 * column name that drifts from the schema (as manage_reminders did) fails
 * silently for every agent until someone notices. This script notices.
 *
 * ── Setup ──────────────────────────────────────────────────────────────
 * Add to `.env.test` in the kabbo/ root (NEVER commit this file):
 *
 *     VITE_SUPABASE_URL=https://<project>.supabase.co
 *     KABBO_TEST_API_KEY=<API key generated by the DEDICATED test user>
 *     KABBO_TEST_TEAM_ID=<optional: a team the test user belongs to>
 *
 * The key must belong to a throwaway account: the script creates, edits and
 * bins a publication named "MCP smoke test" and a reminder attached to it.
 *
 * ── Run ────────────────────────────────────────────────────────────────
 *     npm run test:mcp
 */

import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

function loadEnv() {
  try {
    const raw = readFileSync(resolve('.env.test'), 'utf8');
    const env = {};
    for (const line of raw.split('\n')) {
      const m = line.match(/^\s*([A-Z_][A-Z0-9_]*)\s*=\s*(.*)\s*$/);
      if (m) env[m[1]] = m[2].replace(/^['"]|['"]$/g, '');
    }
    return env;
  } catch {
    console.error('× .env.test not found. See scripts/mcp-smoke-test.mjs for setup.');
    process.exit(2);
  }
}

const env = loadEnv();
for (const k of ['VITE_SUPABASE_URL', 'KABBO_TEST_API_KEY']) {
  if (!env[k]) {
    console.error(`× .env.test is missing ${k}`);
    process.exit(2);
  }
}

const MCP_URL = `${env.VITE_SUPABASE_URL}/functions/v1/mcp-server`;
const HEADERS = {
  'Content-Type': 'application/json',
  Accept: 'application/json, text/event-stream',
  'x-api-key': env.KABBO_TEST_API_KEY,
};

let passed = 0;
let failed = 0;
function ok(label, cond, detail = '') {
  if (cond) {
    console.log(`  ✓ ${label}`);
    passed++;
  } else {
    console.log(`  ✗ ${label}${detail ? ` — ${detail}` : ''}`);
    failed++;
  }
}

let nextId = 1;
async function rpc(method, params = {}) {
  const res = await fetch(MCP_URL, {
    method: 'POST',
    headers: HEADERS,
    body: JSON.stringify({ jsonrpc: '2.0', id: nextId++, method, params }),
  });
  const text = await res.text();
  // Streamable HTTP may answer as SSE; take the last data: line.
  const body = text.startsWith('event:') || text.startsWith('data:')
    ? text.split('\n').filter((l) => l.startsWith('data:')).map((l) => l.slice(5).trim()).pop()
    : text;
  let json;
  try {
    json = JSON.parse(body);
  } catch {
    throw new Error(`Non-JSON response from ${method} (HTTP ${res.status}): ${text.slice(0, 200)}`);
  }
  if (json.error) throw new Error(`${method}: ${JSON.stringify(json.error)}`);
  return json.result;
}

/** Call a tool and return its parsed JSON payload. Throws on isError or {error}. */
async function tool(name, args = {}) {
  const result = await rpc('tools/call', { name, arguments: args });
  const text = result?.content?.find((c) => c.type === 'text')?.text ?? '';
  let data;
  try {
    data = JSON.parse(text);
  } catch {
    data = text;
  }
  if (result?.isError) throw new Error(`${name} returned isError: ${text.slice(0, 300)}`);
  if (data && typeof data === 'object' && 'error' in data) throw new Error(`${name}: ${data.error}`);
  return data;
}

async function step(label, fn) {
  try {
    const value = await fn();
    ok(label, true);
    return value;
  } catch (e) {
    ok(label, false, e.message);
    return undefined;
  }
}

async function run() {
  console.log(`→ ${MCP_URL}`);
  await step('initialize', () => rpc('initialize', {
    protocolVersion: '2025-03-26',
    capabilities: {},
    clientInfo: { name: 'kabbo-smoke', version: '1.0' },
  }));

  const tools = await step('tools/list', () => rpc('tools/list'));
  const names = new Set((tools?.tools ?? []).map((t) => t.name));
  const expected = [
    'list_publications', 'get_publication', 'create_publication', 'update_publication', 'move_stage',
    'delete_publication', 'get_pipeline_summary', 'search_publications', 'bulk_update', 'get_activity_log',
    'manage_reminders', 'get_analytics', 'get_team_summary', 'export_bibtex', 'add_note',
    'get_stalled_papers', 'link_repo', 'set_target_journal', 'import_bibtex', 'manage_related_papers',
    'manage_data_sources',
  ];
  for (const n of expected) ok(`tool registered: ${n}`, names.has(n));
  await step('prompts/list', () => rpc('prompts/list'));
  await step('resources/list', () => rpc('resources/list'));

  const TITLE = 'MCP smoke test';

  // ---- Create → read → update → move → note → links → arrays → reminders → bin
  const created = await step('create_publication', () =>
    tool('create_publication', { title: TITLE, stage: 'draft', authors: ['Smoke Tester'], target_journal: 'Journal of Tests' }));
  const id = created?.publication_id;
  if (!id) {
    console.log('× cannot continue without a publication id');
    return finish();
  }

  const got = await step('get_publication', () => tool('get_publication', { id }));
  ok('create kept target_journal', got?.publication?.target_journal === 'Journal of Tests',
    `got ${got?.publication?.target_journal}`);

  await step('update_publication (target_journal)', () =>
    tool('update_publication', { id, target_journal: 'Journal of Better Tests', notes: 'hello' }));
  const after = await step('get_publication after update', () => tool('get_publication', { id }));
  ok('update kept target_journal', after?.publication?.target_journal === 'Journal of Better Tests');

  await step('move_stage → submitted', () => tool('move_stage', { id, stage: 'submitted' }));
  const moved = await step('get_publication after move', () => tool('get_publication', { id }));
  const hist = moved?.publication?.stage_history ?? [];
  ok('move_stage appended stage_history', Array.isArray(hist) && hist.some((h) => h?.to === 'submitted' && h?.from === 'draft'),
    JSON.stringify(hist).slice(0, 200));

  await step('add_note', () => tool('add_note', { id, note: 'smoke note' }));
  await step('link_repo', () => tool('link_repo', { id, github_repo: 'https://github.com/example/repo' }));
  await step('set_target_journal', () => tool('set_target_journal', { id, journal: 'Journal of Final Tests' }));
  await step('manage_related_papers add', () => tool('manage_related_papers', { id, action: 'add', value: 'doi:10.1000/x' }));
  await step('manage_data_sources add', () => tool('manage_data_sources', { id, action: 'add', value: 'https://example.org/data' }));
  await step('bulk_update', () => tool('bulk_update', { updates: [{ id, themes: ['smoke'] }] }));

  const reminder = await step('manage_reminders create', () =>
    tool('manage_reminders', { action: 'create', publication_id: id, title: 'Smoke reminder', due_date: '2030-01-01', reminder_type: 'custom' }));
  ok('reminder type normalised to a valid value', reminder?.reminder?.reminder_type === 'general',
    `got ${reminder?.reminder?.reminder_type}`);
  const list = await step('manage_reminders list', () => tool('manage_reminders', { action: 'list' }));
  ok('created reminder appears in list', (list?.reminders ?? []).some((r) => r.id === reminder?.reminder?.id));
  if (reminder?.reminder?.id) {
    await step('manage_reminders complete', () => tool('manage_reminders', { action: 'complete', reminder_id: reminder.reminder.id }));
    await step('manage_reminders delete', () => tool('manage_reminders', { action: 'delete', reminder_id: reminder.reminder.id }));
  }
  await step('manage_reminders rejects missing due_date', async () => {
    const r = await rpc('tools/call', { name: 'manage_reminders', arguments: { action: 'create', title: 'no date' } });
    const text = r?.content?.[0]?.text ?? '';
    if (!/due_date is required/.test(text)) throw new Error(`expected a due_date error, got ${text.slice(0, 120)}`);
  });

  // ---- Read-only tools
  await step('list_publications', () => tool('list_publications', { query: 'smoke' }));
  await step('search_publications', () => tool('search_publications', { query: 'smoke', author: 'Tester' }));
  await step('get_pipeline_summary', () => tool('get_pipeline_summary'));
  await step('get_stalled_papers', () => tool('get_stalled_papers', { days: 0 }));
  await step('get_analytics', () => tool('get_analytics', { breakdown_by: 'author' }));
  const log = await step('get_activity_log', () => tool('get_activity_log', { days: 1, source: 'mcp' }));
  ok('activity log attributes this run to source=mcp', (log?.entries ?? []).length > 0, `got ${log?.entries?.length ?? 0} rows`);
  await step('export_bibtex', () => tool('export_bibtex', { ids: [id] }));
  await step('import_bibtex', () => tool('import_bibtex', {
    bibtex: `@article{smoke, title = {${TITLE}}, author = {Smoke Tester}, year = {2024}, journal = {Journal of Imports}}`,
    stage: 'submitted',
  }));
  if (env.KABBO_TEST_TEAM_ID) {
    await step('get_team_summary', () => tool('get_team_summary', { team_id: env.KABBO_TEST_TEAM_ID }));
  } else {
    console.log('  – get_team_summary skipped (set KABBO_TEST_TEAM_ID to include it)');
  }

  // ---- Cleanup
  await step('delete_publication (to bin)', () => tool('delete_publication', { id }));
  return finish();
}

function finish() {
  console.log(`\n${passed} passed, ${failed} failed`);
  process.exit(failed ? 1 : 0);
}

run().catch((e) => {
  console.error('× fatal:', e.message);
  process.exit(1);
});
